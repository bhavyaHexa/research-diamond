// Generates auth/auth.config.js from APP_AUTH_SECRET: a salted PBKDF2 hash that the
// browser checks the entered key against, so the secret itself is never shipped.
// The process environment wins (CI / live server); otherwise the project's .env is read.
//   node auth/build-auth.mjs
import { pbkdf2Sync, randomBytes } from "node:crypto";
import { existsSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

// Must match auth/auth.js (PBKDF2, SHA-256, 32-byte result).
const ITERATIONS = 210000;
const KEY_BYTES = 32;

const here = dirname(fileURLToPath(import.meta.url));
const envFile = join(here, "..", ".env");
if (!process.env.APP_AUTH_SECRET && existsSync(envFile)) process.loadEnvFile(envFile);

const secret = process.env.APP_AUTH_SECRET?.trim();
if (!secret) {
  console.error("APP_AUTH_SECRET is not set (in the environment or .env).");
  process.exit(1);
}

const salt = randomBytes(16).toString("hex");
const hash = pbkdf2Sync(secret, salt, ITERATIONS, KEY_BYTES, "sha256").toString("hex");
const out = join(here, "auth.config.js");
writeFileSync(
  out,
  `// Generated by auth/build-auth.mjs - do not edit or commit.\n` +
    `export const AUTH = ${JSON.stringify({ salt, iterations: ITERATIONS, hash }, null, 2)};\n`,
);
console.log(`Wrote ${out}`);
